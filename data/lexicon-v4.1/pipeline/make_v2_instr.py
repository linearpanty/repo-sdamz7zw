#!/usr/bin/env python3
"""Recreates v2_instr.py (INSTR / W_KEEP / W_RUBRIC regex lists) verbatim from the read-only v2 script
01v2_clean_segment.py (the block from 'INSTR = rx(' up to the line before 'TESTNO ='; L72-104 of that file).
01_segment_v3.py originally exec'd a copy in the system temp directory, which did not exist; v3 and v4 exec ./v2_instr.py."""
import sys, os
src = sys.argv[1] if len(sys.argv) > 1 else '../v3-inputs/candidate-2026-10-30-v2/01v2_clean_segment.py'
L = open(src, encoding='utf-8').read().split('\n')
a = next(i for i, l in enumerate(L) if l.startswith('INSTR = rx('))
b = next(i for i, l in enumerate(L) if l.startswith('TESTNO ='))
open('v2_instr.py', 'w', encoding='utf-8').write(f'# AUTO-GENERATED by make_v2_instr.py from {os.path.basename(src)} L{a+1}-{b}; do not edit\n' + '\n'.join(L[a:b]) + '\n')
print(f'v2_instr.py: L{a+1}-{b} of {src}')
